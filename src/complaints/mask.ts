// 리포트(HTML·CSV·시트)와 관리자 화면에 넣는 인용문에서 개인정보를 가린다.
// 공개 게시판 글이라도 리포트는 사내 문서라 한 번 더 가린다. 이름·아이디는 리포트에 아예 넣지 않는다.
// 순서가 중요하다: 긴 번호(주민·주문)를 먼저 가려야 전화·계좌 규칙이 그 일부만 먹지 않는다.
// 치수·날짜("178cm 105kg 3XL", "2026-10-27")는 남긴다.

const SEP = "[-.\\s]*";

const RULES: [RegExp, string][] = [
  // 이메일
  [/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, "[이메일]"],
  // SNS 아이디(@shop_lover)
  [/(?<![\w.])@[A-Za-z0-9_.]{2,}/g, "[아이디]"],
  // 이름표가 붙은 이름·아이디: "입금자명 박영희", "받는 분 김철수", "카톡 아이디 abc_123", "주문자: 홍길동"
  [
    // 이름표 뒤에 띄어쓰기나 쌍점이 있어야 한다("아이디어", "카톡으로", "OUTSIDE"는 건드리지 않음).
    /(?<![A-Za-z가-힣])((?:카톡|카카오톡|인스타(?:그램)?|회원)\s*(?:아이디|ID)|주문자|구매자|받는\s*(?:분|사람)|수령인|수취인|입금자명?|예금주|성함|닉네임|아이디|ID|카톡|카카오톡|인스타)(?:\s*[:：]\s*|\s+)[^\s,.!?]+/g,
    "$1 [가림]",
  ],
  // 주민등록번호(900101-1234567, 9001011234567)
  [/(?<!\d)\d{6}-?[1-4]\d{6}(?!\d)/g, "[주민번호]"],
  // 주문번호(카페24: 20261021-0000150, 하이픈 없이도)
  [/(?<!\d)20\d{6}[-\s]?\d{7}(?!\d)/g, "[주문번호]"],
  // 휴대전화·일반 전화: 010-1234-5678, 010 1234 5678, 01012345678, +82 10-1234-5678, 02-123-4567
  [new RegExp(`(?<![\\d+])(?:\\+82${SEP}0?|0)(?:1[016789]|2|[3-6][1-5]|70)${SEP}\\d{3,4}${SEP}\\d{4}(?!\\d)`, "g"), "[전화번호]"],
  // 계좌번호처럼 보이는 숫자 묶음(110-123-456789, 1002-123-456789). 마지막 묶음이 세 자리 이상이라 날짜(2026-10-27)는 두고 넘어간다.
  [/(?<!\d)\d{3,6}-\d{2,6}-\d{3,8}(?:-\d{1,6})?(?!\d)/g, "[계좌번호]"],
  // 하이픈 없이 길게 붙은 숫자(계좌·송장 등 10~16자리)
  [/(?<!\d)\d{10,16}(?!\d)/g, "[번호]"],
  // 시·도로 시작하는 주소: 로·길·동 + 번지까지
  [
    /(서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|충청|전북|전남|전라|경북|경남|경상|제주)[^\n,.!?]{0,40}?(로|길|동|읍|면|리)\s*\d+(-\d+)?(\s*[^\n,.!?]{0,20}?(호|층|동))?/g,
    "[주소]",
  ],
  // 시·도 없이 도로명만 쓴 주소(테헤란로 123, 중앙로45번길 12). 번지 뒤에는 띄어쓰기·문장부호·조사(으로·에·입니다)만 온다.
  // 단위가 바로 붙으면(사이즈로 2XL, 출구로 5분, 택배로 2개) 주소가 아니다.
  [/[가-힣0-9]+(로|길)(\s*\d+번?길)?\s*\d{1,4}(-\d{1,4})?(?=$|[\s,.)!?]|으로|로|에|이에요|입니다|이고|인데)/g, "[주소]"],
  // 아파트 동·호(101동 1203호)
  [/\d{1,4}\s*동\s*\d{1,4}\s*호/g, "[주소]"],
];

export function maskPersonalInfo(text: string): string {
  return RULES.reduce((out, [pattern, replacement]) => out.replace(pattern, replacement), text);
}
